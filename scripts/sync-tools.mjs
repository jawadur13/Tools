// Regenerates src/tools/registry.ts, src/tools/loaders.tsx and
// src/components/ToolIcon.tsx from the folders in src/tools/.
//
//   npm run tools:sync
//
// Tools keep their current position in the registry; new ones are appended
// to the end of their category (popular tools first).
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const toolsDir = path.join(root, "src/tools");
const read = (p) => fs.readFileSync(path.join(root, p), "utf8");

const categoryOrder = [...read("src/tools/categories.ts").matchAll(/slug: "([\w-]+)"/g)].map((m) => m[1]);

const tools = fs
  .readdirSync(toolsDir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && fs.existsSync(path.join(toolsDir, d.name, "meta.ts")))
  .map(({ name }) => {
    const meta = fs.readFileSync(path.join(toolsDir, name, "meta.ts"), "utf8");
    const field = (key) => meta.match(new RegExp(`${key}: "([^"]+)"`))?.[1];
    if (!fs.existsSync(path.join(toolsDir, name, "Tool.tsx"))) throw new Error(`${name}: missing Tool.tsx`);
    if (field("slug") !== name) throw new Error(`${name}: slug in meta.ts must match the folder name`);
    const category = field("category");
    if (!categoryOrder.includes(category)) throw new Error(`${name}: unknown category "${category}"`);
    return { slug: name, category, icon: field("icon"), popular: /popular: true/.test(meta) };
  });

const previous = [...read("src/tools/registry.ts").matchAll(/from "\.\/([\w-]+)\/meta"/g)].map((m) => m[1]);
const rank = (t) => {
  const i = previous.indexOf(t.slug);
  return i === -1 ? previous.length + (t.popular ? 0 : 1000) : i;
};
tools.sort(
  (a, b) => categoryOrder.indexOf(a.category) - categoryOrder.indexOf(b.category) || rank(a) - rank(b) || a.slug.localeCompare(b.slug),
);

const ident = (slug) => slug.replace(/-(\w)/g, (_, c) => c.toUpperCase());

const registry = `// Generated by scripts/sync-tools.mjs — run \`npm run tools:sync\` after adding a tool.
import type { ToolMeta } from "./types";
${tools.map((t) => `import { meta as ${ident(t.slug)} } from "./${t.slug}/meta";`).join("\n")}

/** Every tool on the site, most important first within each category. */
export const tools: ToolMeta[] = [
${tools.map((t) => `  ${ident(t.slug)},`).join("\n")}
];

export function getTool(slug: string): ToolMeta | undefined {
  return tools.find((t) => t.slug === slug);
}

export function getToolsByCategory(category: string): ToolMeta[] {
  return tools.filter((t) => t.category === category);
}

/** Same-category tools first, then popular ones, excluding the tool itself. */
export function getRelatedTools(tool: ToolMeta, limit = 4): ToolMeta[] {
  const others = tools.filter((t) => t.slug !== tool.slug);
  const sameCategory = others.filter((t) => t.category === tool.category);
  const popular = others.filter((t) => t.category !== tool.category && t.popular);
  const rest = others.filter((t) => t.category !== tool.category && !t.popular);
  return [...sameCategory, ...popular, ...rest].slice(0, limit);
}
`;

// next/dynamic needs its options written inline at every call site.
const loaders = `// Generated by scripts/sync-tools.mjs — run \`npm run tools:sync\` after adding a tool.
"use client";

import dynamic from "next/dynamic";
import type { ComponentType } from "react";
import { ToolSkeleton } from "@/components/ToolSkeleton";

/** Each tool's UI is code-split, so a page only downloads its own tool. */
const loaders: Record<string, ComponentType> = {
${tools.map((t) => `  "${t.slug}": dynamic(() => import("./${t.slug}/Tool"), { ssr: false, loading: () => <ToolSkeleton /> }),`).join("\n")}
};

export function ToolRenderer({ slug }: { slug: string }) {
  const Tool = loaders[slug];
  return Tool ? <Tool /> : null;
}
`;

const icons = [...new Set(tools.map((t) => t.icon))].sort();
const iconFile = `// Generated by scripts/sync-tools.mjs — run \`npm run tools:sync\` after adding a tool.
import {
${[...new Set([...icons, "Wrench"])].sort().map((n) => `  ${n},`).join("\n")}
  type LucideProps,
} from "lucide-react";
import type { ComponentType } from "react";

// Icons are imported explicitly so only the ones in use are bundled.
const icons: Record<string, ComponentType<LucideProps>> = {
${icons.map((n) => `  ${n},`).join("\n")}
};

export function ToolIcon({ name, ...props }: { name: string } & LucideProps) {
  const Icon = icons[name] ?? Wrench;
  return <Icon {...props} />;
}
`;

// "use client" must stay the first statement, so move the banner below it.
const fixDirective = (src) => src.replace(/^(\/\/.*\n)("use client";\n)/, "$2$1");

fs.writeFileSync(path.join(root, "src/tools/registry.ts"), registry);
fs.writeFileSync(path.join(root, "src/tools/loaders.tsx"), fixDirective(loaders));
fs.writeFileSync(path.join(root, "src/components/ToolIcon.tsx"), iconFile);

const counts = categoryOrder.map((c) => `${c}: ${tools.filter((t) => t.category === c).length}`).join(", ");
console.log(`Synced ${tools.length} tools (${counts}), ${icons.length} icons.`);
